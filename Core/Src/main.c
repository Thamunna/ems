/******************************************************************************
 * Function:    _write
 * Description: Override for printf() output via USB CDC.
 *              If USB is not connected or busy, data is silently dropped.
 * Parameters:  file - File descriptor (unused)
 *              ptr  - Pointer to output data
 *              len  - Number of bytes to output
 * Returns:     int  - Number of bytes written (always returns len)
 ******************************************************************************/
int _write(int file, char *ptr, int len)
{
	if (hUsbDeviceFS.dev_state != USBD_STATE_CONFIGURED)	  /* USB not connected or not ready → drop data */
	{
		return len;
	}

	if (CDC_Transmit_FS((uint8_t*)ptr, len) == USBD_OK)	 /* Try once, non-blocking */
	{
		return len;
	}
	return len;	/* USB busy → drop this printf */
}

