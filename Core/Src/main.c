/******************************************************************************
 * Function:    HAL_UART_ErrorCallback
 * Description: UART error callback. Clears errors and restarts DMA reception.
 * Parameters:  huart - Pointer to UART handle
 * Returns:     None
 ******************************************************************************/
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
	if (huart->Instance == USART1)
	{
		__HAL_UART_CLEAR_PEFLAG(huart);         /* Clear UART parity/noise/overrun/framing error flags */
		HAL_UART_AbortReceive(huart);           /* Abort DMA safely */
		HAL_UARTEx_ReceiveToIdle_DMA(huart, RxData, sizeof(RxData));  /* Restart DMA reception */
		__HAL_DMA_DISABLE_IT(huart->hdmarx, DMA_IT_HT);               /* Disable Half Transfer interrupt */
	}
}

/******************************************************************************
 * Function:    HAL_UARTEx_RxEventCallback
 * Description: UART Receive to Idle Event Callback. Processes received Modbus
 *              frames when an Idle Line is detected or Rx buffer is full.
 * Parameters:  huart - Pointer to UART handle
 *              Size  - Number of bytes received
 * Returns:     None
 ******************************************************************************/
void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
	if (huart->Instance == USART1)
	{
		if (RxData[0] == SLAVE_ID)
		{
			switch (RxData[1])
			{
			case 0x03:
				readHoldingRegs();
				break;
			case 0x04:
				readInputRegs();
				break;
			case 0x06:
				writeSingleReg();
				break;
			case 0x10:
				writeHoldingRegs();
				break;
			default:
				modbusException(ILLEGAL_FUNCTION);
				break;
			}
		}
	}
	HAL_UARTEx_ReceiveToIdle_DMA(&huart1, RxData, sizeof(RxData));
	__HAL_DMA_DISABLE_IT(huart1.hdmarx, DMA_IT_HT);
}
